        <div class="lc-prose">
          <p>
            Nuestra relación con el país se ha construido a lo largo de los años y de
            múltiples encuentros. Zona Maco ha sido una parte importante de ese recorrido,
            pero también lo han sido las visitas, los artistas, la escena cultural y todas
            las conversaciones que, de una manera u otra, nos han hecho volver.
          </p>
          <p>
            Ahora, esa relación toma una nueva forma. Desde Ciudad de México, La Cometa
            desarrolla un espacio de encuentro y de exploración, abierto a nuevas propuestas,
            artistas y colaboraciones.
          </p>
          <p>
            Esta nueva etapa inicia en 2026 con una colaboración junto a los artistas
            mexicanos Marek Wolfryd y Anuar Maauad, con quienes La Cometa ha venido
            construyendo una relación, y continuará extendiéndose hacia nuevos artistas y
            proyectos.
          </p>
          <blockquote class="lc-pull">
            La Oficina de Proyectos nace como un espacio para el encuentro, la exploración y
            el desarrollo de nuevas propuestas.
          </blockquote>
        </div>

