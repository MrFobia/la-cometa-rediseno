      <div>
        <h2 id="h-texto" class="text-[length:var(--text-3xl)] mb-8">Texto curatorial</h2>

        <blockquote class="lc-pull mb-10">
          La puerta rompe el espacio, impide la osmosis, impone los tabiques: por un lado,
          estoy yo y mi casa, por el otro están los demás, el mundo, lo público, lo político.
          <footer>Georges Perec, <cite>Especies de espacios</cite></footer>
        </blockquote>

        <div class="lc-prose">
          <p>
            Las puertas que pinta Dámaxo Henao permanecen cerradas. Carecen de cerradura y
            de manija, cualquier señal que permita abrirlas, y esa sustracción, que tarda un
            momento en advertirse, va instalando en quien mira una extrañeza difícil de
            sujetar. Algo se guarda en el centro de cada composición, algo que hace que la
            tarde se suspenda.
          </p>
          <p>
            Caminar por una calle a la hora en que el sol se recuesta sobre los muros, pasar
            frente a una casa ajena y quedarse viéndola con la sospecha de que la fachada
            dice algo de la vida que esconde. La puerta rompe el espacio, levanta el tabique
            detrás del cual comienza lo propio, y en ese gesto administra la frontera de lo
            habitable, decidiendo qué entra y qué permanece afuera. Las puertas de Dámaxo
            custodian volúmenes a los que nadie entrará; guardianas de una intimidad sin carne.
          </p>
          <p>
            El ornamento de una fachada, la vegetación que se asoma por encima de un muro,
            las sombras sobre las barandas parecen darle a cada puerta su carácter: la
            convierten en transeúnte, centinela, ermitaña. Pero esos cuerpos solo pueden ser
            tocados por un único visitante, la luz. Y la pintura registra ese encuentro con
            el cuidado de quien ha mirado muchas veces la misma cuadra a la misma hora, y ha
            reparado en lo que se filtra por los bordes.
          </p>
          <p>Somos nosotros esa espera, frente a una casa que no es la nuestra.</p>
        </div>
      </div>

